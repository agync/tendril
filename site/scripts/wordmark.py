#!/usr/bin/env python3
"""Outline the wordmark, lowercase "tendril" in IBM Plex Mono 600 with -3% tracking.

    wordmark.py <font.woff2> <out.svg>

Writes the glyphs as one path in font units, baseline at y=0, so standalone logo SVGs depend on
no web font. brand.mjs reads the path and the data-* metrics. Run it only when the font or the
tracking changes; it needs fontTools and brotli, which the render container does not carry.
"""

import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

TEXT = "tendril"
TRACKING = -0.03


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    font = TTFont(sys.argv[1])
    upm = font["head"].unitsPerEm
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    track = round(TRACKING * upm)

    pen = SVGPathPen(glyphs, lambda v: f"{v:g}")
    bounds = BoundsPen(glyphs)
    x = 0
    for i, char in enumerate(TEXT):
        name = cmap[ord(char)]
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))
        glyphs[name].draw(TransformPen(bounds, (1, 0, 0, -1, x, 0)))
        x += glyphs[name].width + (track if i < len(TEXT) - 1 else 0)

    os2 = font["OS/2"]
    ink = " ".join(f"{v:g}" for v in bounds.bounds)
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" '
        f'viewBox="0 {-os2.sCapHeight - 60} {x} {os2.sCapHeight + 60 + 40}" '
        f'data-upm="{upm}" data-advance="{x}" data-x-height="{os2.sxHeight}" '
        f'data-cap-height="{os2.sCapHeight}" data-ink="{ink}">\n'
        "  <!-- Generated by site/scripts/wordmark.py from IBM Plex Mono 600 (SIL OFL 1.1). -->\n"
        f'  <path d="{pen.getCommands()}"/>\n'
        "</svg>\n"
    )
    with open(sys.argv[2], "w", encoding="utf-8") as out:
        out.write(svg)


if __name__ == "__main__":
    main()
