def load_tokens(path: str) -> dict:
    tokens = json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
    light, dark = tokens["light"], tokens["dark"]
    if light.keys() != dark.keys():
        sys.exit("build.py: tokens.json light and dark name different tokens")
    return tokens


def block(selector: str, decls: dict, scheme: str, indent: str = "") -> str:
    lines = [f"{indent}{selector} {{", f"{indent}  color-scheme: {scheme};"]
    lines += [f"{indent}  {name}: {value};" for name, value in decls.items()]
    return "\n".join(lines + [f"{indent}}}"])


def themed(decls_for: callable) -> str:
    """Light by default, dark when the system asks unless the reader chose light, dark when chosen."""
    return "\n\n".join(
        [
            block(":root", decls_for("light"), "light"),
            "@media (prefers-color-scheme: dark) {\n"
            + block(':root:not([data-theme="light"])', decls_for("dark"), "dark", "  ")
            + "\n}",
            block(':root[data-theme="dark"]', decls_for("dark"), "dark"),
        ]
    )


def site_tokens_css(tokens: dict) -> str:
    head = "/* Generated by build.py from site/tokens.json. Edit that file, not this one. */\n\n"
    return head + themed(lambda mode: {f"--{k}": v for k, v in tokens[mode].items()}) + "\n"


def docs_tokens_css(tokens: dict, base: str) -> str:
    head = "/* Generated by build.py from site/tokens.json and docs-theme/tokens.base.css. */\n\n"
    colours = themed(lambda mode: {k: tokens[mode][v] for k, v in DOCS_COLOURS.items()})
    return head + base.rstrip() + "\n\n" + colours + "\n"


def tokens_cmd(args: argparse.Namespace) -> None:
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(site_tokens_css(load_tokens(args.tokens)), encoding="utf-8")


def theme(args: argparse.Namespace) -> None:
    src = pathlib.Path(args.theme)
    out = pathlib.Path(args.out)
    shutil.rmtree(out, ignore_errors=True)
    shutil.copytree(src, out, ignore=shutil.ignore_patterns("tokens.base.css"))
    base = (src / "tokens.base.css").read_text(encoding="utf-8")
    (out / "assets" / "tokens.css").write_text(
        docs_tokens_css(load_tokens(args.tokens), base), encoding="utf-8"
    )
    fonts = out / "assets" / "fonts"
    fonts.mkdir(parents=True, exist_ok=True)
    for font in pathlib.Path(args.fonts).iterdir():
        if font.suffix in (".woff2", ".txt"):
            shutil.copy2(font, fonts / font.name)


def script_hashes(docs: pathlib.Path) -> list[str]:
    hashes = set()
    for page in docs.rglob("*.html"):
        for attrs, body in INLINE_SCRIPT.findall(page.read_text(encoding="utf-8")):
            if "application/json" in attrs or "application/ld+json" in attrs:
                continue
            digest = hashlib.sha256(body.encode("utf-8")).digest()
            hashes.add("'sha256-" + base64.b64encode(digest).decode("ascii") + "'")
    return sorted(hashes)


def assemble(args: argparse.Namespace) -> None:
    site = pathlib.Path(args.site)
    dist = pathlib.Path(args.dist)
    url = args.site_url.rstrip("/")
    if not re.fullmatch(r"https://[a-z0-9.-]+(:[0-9]+)?", url):
        sys.exit(f"build.py: SITE_URL must be an https origin with no path, got {url!r}")

    shutil.rmtree(dist, ignore_errors=True)
    dist.mkdir(parents=True)
    shutil.copytree(site / "assets", dist / "assets")
    (dist / "assets" / "css" / "tokens.css").write_text(
        site_tokens_css(load_tokens(str(site / "tokens.json"))), encoding="utf-8"
    )

    # Each stylesheet and script is linked with a hash of its contents, so a deploy never leaves a
    # browser on a cached copy that no longer matches the page.
    versions = {}
    for asset in sorted((dist / "assets").glob("*/*")):
        if asset.suffix in (".css", ".js"):
            digest = hashlib.sha256(asset.read_bytes()).hexdigest()[:10]
            versions["/" + asset.relative_to(dist).as_posix()] = digest

    for name in PAGES:
        text = (site / name).read_text(encoding="utf-8")
        for path, digest in versions.items():
            text = text.replace(f'"{path}"', f'"{path}?v={digest}"')
        if INLINE_SCRIPT.search(text) or re.search(r"<style|\sstyle=", text):
            sys.exit(f"build.py: {name} has an inline script or style; the policy forbids it")
        text = text.replace("{{SITE_URL}}", url)
        if "{{" in text:
            sys.exit(f"build.py: {name} has an unfilled placeholder")
        (dist / name).write_text(text, encoding="utf-8")
    for name in STATIC:
        shutil.copy2(site / name, dist / name)

    rendered = pathlib.Path(args.render) / "docs"
    if not (rendered / "index.html").is_file():
        sys.exit(f"build.py: no rendered docs at {rendered}")
    shutil.copytree(rendered, dist / "docs")
    # The theme's head slot carries the site origin, which must be absolute.
    for page in (dist / "docs").rglob("*.html"):
        text = page.read_text(encoding="utf-8")
        if "{{SITE_URL}}" in text:
            page.write_text(text.replace("{{SITE_URL}}", url), encoding="utf-8")

    hashes = script_hashes(dist / "docs")
    headers = (site / "_headers").read_text(encoding="utf-8")
    (dist / "_headers").write_text(
        headers.replace("@DOCS_SCRIPT_HASHES@", " ".join(hashes)), encoding="utf-8"
    )

    files = sum(1 for p in dist.rglob("*") if p.is_file())
    print(f"build.py: {dist} ready, {files} files, {len(hashes)} docs script hashes, site {url}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)

    k = sub.add_parser("tokens")
    k.add_argument("tokens")
    k.add_argument("out")
    k.set_defaults(run=tokens_cmd)

    t = sub.add_parser("theme")
    t.add_argument("theme")
    t.add_argument("fonts")
    t.add_argument("tokens")
    t.add_argument("out")
    t.set_defaults(run=theme)

    a = sub.add_parser("assemble")
    a.add_argument("--site-url", required=True)
    a.add_argument("--render", required=True)
    a.add_argument("site")
    a.add_argument("dist")
    a.set_defaults(run=assemble)

    args = parser.parse_args()
    args.run(args)


if __name__ == "__main__":
    main()
